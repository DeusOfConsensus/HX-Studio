import { useEffect, useMemo, useRef } from "react";
import { Canvas, useThree } from "@react-three/fiber";
import * as THREE from "three";
import { evaluate, effectiveGeometry } from "../../simulation/solvers/exchangerSolver";
import { sampleConfiguration } from "../../engineering/sampleConfiguration";
import { useView } from "../../state/viewStore";
import { tubeLayout } from "../../three/geometries/layout";
import { ExchangerAssembly } from "../../three/scenes/ExchangerAssembly";
import { ErrorBoundary } from "../ErrorBoundary";

function PresentationState({ reducedMotion }: { reducedMotion: boolean }) {
  const setView = useView((s) => s.setView);
  const original = useRef<ReturnType<typeof useView.getState> | null>(null);
  useEffect(() => {
    if (original.current === null) original.current = useView.getState();
    setView({
      selected: null, selectedTube: null, hidden: {}, isolated: null,
      shellOpacity: 0.25, explode: 0, clipOn: false, clipPos: 0,
      running: !reducedMotion, speed: 0.8, density: 0.55,
      showFlow: true, showThermal: true, showTempLabels: false, showNames: false,
      quality: "low",
    });
  }, [reducedMotion, setView]);
  useEffect(() => () => {
    const s = original.current;
    if (!s) return;
    useView.setState({
      selected: s.selected, selectedTube: s.selectedTube, hidden: s.hidden, isolated: s.isolated,
      shellOpacity: s.shellOpacity, explode: s.explode, clipOn: s.clipOn, clipPos: s.clipPos,
      running: s.running, speed: s.speed, density: s.density,
      showFlow: s.showFlow, showThermal: s.showThermal, showTempLabels: s.showTempLabels,
      showNames: s.showNames, quality: s.quality,
    });
  }, []);
  return null;
}

function PresentationCamera({ g }: { g: ReturnType<typeof effectiveGeometry> }) {
  const { camera, size } = useThree();
  useEffect(() => {
    if (!(camera instanceof THREE.PerspectiveCamera)) return;
    const d = Math.hypot(g.L / 2 + 0.55, g.Ds / 2 + 0.4);
    const vHalf = THREE.MathUtils.degToRad(camera.fov) / 2;
    const hHalf = Math.atan(Math.tan(vHalf) * (size.width / size.height));
    const zoom = size.width < 700 ? 0.48 : 0.52;
    const distance = d / Math.sin(Math.min(vHalf, hHalf)) * zoom;
    camera.position.set(distance * 0.38, distance * 0.26, distance * 0.9);
    camera.lookAt(0, 0, 0);
    camera.updateProjectionMatrix();
  }, [camera, g, size.width, size.height]);
  return null;
}

export function HeroExchanger({ reducedMotion }: { reducedMotion: boolean }) {
  const input = sampleConfiguration;
  const g = useMemo(() => effectiveGeometry(input.geometry), []);
  const layout = useMemo(() => tubeLayout(g), [g]);
  const ev = useMemo(() => evaluate(input), []);
  return <div className="hero-exchanger" role="img" aria-label="Three-dimensional procedural shell-and-tube exchanger generated by the same parametric model and solver visualization used in the simulator">
    <div className="hero-engineering-ring ring-one" aria-hidden="true" />
    <div className="hero-engineering-ring ring-two" aria-hidden="true" />
    <ErrorBoundary>
      <Canvas
        dpr={reducedMotion ? 1 : [1, 1.4]}
        frameloop={reducedMotion ? "demand" : "always"}
        camera={{ fov: 36, near: 0.01, far: 100, position: [4, 3, 7] }}
        gl={{ antialias: !reducedMotion, powerPreference: "low-power", alpha: false }}
        fallback={<div className="hero-webgl-fallback">Interactive 3D model unavailable in this browser.</div>}
      >
        <PresentationState reducedMotion={reducedMotion}/>
        <color attach="background" args={["#071722"]}/>
        <ambientLight intensity={1.25}/>
        <hemisphereLight args={["#c9e2ef", "#20313d", 0.66]}/>
        <directionalLight position={[4, 6, 5]} intensity={1.9}/>
        <directionalLight position={[-4, -2, -3]} intensity={0.7} color="#53bed0"/>
        <ExchangerAssembly g={g} layout={layout} ev={ev}/>
        <PresentationCamera g={g}/>
      </Canvas>
    </ErrorBoundary>
  </div>;
}
